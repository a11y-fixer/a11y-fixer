function confClass(conformance: string): string {
  switch (conformance) {
    case 'Supports':
      return 'conf-supports';
    case 'Partially Supports':
      return 'conf-partial';
    case 'Does Not Support':
      return 'conf-none';
    default:
      return '';
  }
}

function draftBanner(meta: DocumentMeta): string {
  if (meta.published) return '';
  return `<div class="draft-banner" role="status">DRAFT — not for distribution. This conformance document reflects an unpublished audit and may change.</div>`;
}

function footer(meta: DocumentMeta): string {
  return `<footer>Generated by a11y-fixer on ${esc(meta.date)} from commit ${esc(meta.headSha)}. ${
    meta.published ? 'Published conformance document.' : 'Draft — not published.'
  }</footer>`;
}

function page(title: string, meta: DocumentMeta, inner: string): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>${STYLE}</style>
</head>
<body>
<main class="doc">
${draftBanner(meta)}
${inner}
${footer(meta)}
</main>
</body>
</html>`;
}

function renderAcr(doc: AcrDocument): string {
  const summary = doc.summary
    .map(s => `<dt>${esc(s.label)}</dt><dd>${esc(s.value)}</dd>`)
    .join('\n');

  const tables = doc.tables
    .map(t => {
      const note = t.note ? `<p class="note">${esc(t.note)}</p>` : '';
      if (t.rows.length === 0) {
        return `<h2>${esc(t.title)}</h2>${note}`;
      }
      const rows = t.rows
        .map(
          r => `<tr>
  <td><strong>${esc(r.wcagId)}</strong> ${esc(r.title)} <span class="note">(Level ${esc(r.level)})</span></td>
  <td class="conf ${confClass(r.conformance)}">${esc(r.conformance)}</td>
  <td>${esc(r.remarks)}</td>
</tr>`,
        )
        .join('\n');
      return `<h2>${esc(t.title)}</h2>${note}
<table>
<thead><tr><th>Criteria</th><th>Conformance Level</th><th>Remarks and Explanations</th></tr></thead>
<tbody>
${rows}
</tbody>
</table>`;
    })
    .join('\n');

  const inner = `<h1>Accessibility Conformance Report</h1>
<p class="note">VPAT 2.5 (INT) — based on the Voluntary Product Accessibility Template</p>
<dl class="summary">
${summary}
</dl>
${tables}`;
  return page(`ACR — ${doc.meta.productName}`, doc.meta, inner);
}

function renderStatement(doc: StatementDocument): string {
  const sections = doc.sections
    .map(s => {
      const paras = s.paragraphs.map(p => `<p>${esc(p)}</p>`).join('\n');
      const items = s.items && s.items.length
        ? `<ul class="limits">${s.items.map(i => `<li>${esc(i)}</li>`).join('\n')}</ul>`
        : '';
      return `<h2>${esc(s.heading)}</h2>\n${paras}\n${items}`;
    })
    .join('\n');

  const inner = `<h1>Accessibility Statement</h1>
<p class="note">${esc(doc.meta.productName)} · ${esc(doc.meta.date)}</p>
${sections}`;
  return page(`Accessibility Statement — ${doc.meta.productName}`, doc.meta, inner);
}

function renderRoadmap(doc: RemediationRoadmapDocument): string {
  const groups = doc.groups
    .map(g => {
      const rows = g.items
        .map(
          i => `<tr>
  <td><strong>${esc(i.wcagId)}</strong> ${esc(i.title)} <span class="note">(Level ${esc(i.level)})</span></td>
  <td class="conf">${esc(i.status)}</td>
  <td>${esc(i.remark)}</td>
</tr>`,
        )
        .join('\n');
      return `<h2>${esc(g.heading)}</h2>
<p class="note">${esc(g.note)}</p>
<table>
<thead><tr><th>Criteria</th><th>Status</th><th>Remediation / remarks</th></tr></thead>
<tbody>
${rows}
</tbody>
</table>`;
    })
    .join('\n');

  const inner = `<h1>Accessibility Remediation Roadmap</h1>
<p class="note">${esc(doc.meta.productName)} · ${esc(doc.meta.date)}</p>
<p>${esc(doc.intro)}</p>
${groups}`;
  return page(`Remediation Roadmap — ${doc.meta.productName}`, doc.meta, inner);
}

function renderLetter(doc: ConformanceLetterDocument): string {
  const paras = doc.paragraphs.map(p => `<p>${esc(p)}</p>`).join('\n');
  const sig = doc.signature.map(line => `<div>${esc(line)}</div>`).join('\n');
  const inner = `<h1>Letter of Accessibility Conformance</h1>
<p class="note">${esc(doc.meta.productName)}</p>
<div class="letter">
${paras}
<div class="signature">
<div>Sincerely,</div>
${sig}
</div>
</div>`;
  return page(`Conformance Letter — ${doc.meta.productName}`, doc.meta, inner);
}

/** Render any conformance document to a standalone HTML string. */
export function renderDocumentHtml(doc: ConformanceDocument): string {
  switch (doc.kind) {
    case 'acr':
      return renderAcr(doc);
    case 'statement':
      return renderStatement(doc);
    case 'roadmap':
      return renderRoadmap(doc);
    case 'letter':
      return renderLetter(doc);
    default: {
      // Exhaustiveness: a new DocumentKind must get its own renderer, not fall
      // through to the statement branch silently.
      const _never: never = doc;
      throw new Error(`unhandled document kind: ${(_never as ConformanceDocument).kind}`);
    }
  }
}
